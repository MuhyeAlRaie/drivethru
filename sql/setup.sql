-- درايف ثرو | إعداد قاعدة البيانات في Supabase
-- ------------------------------------------------------------
-- طريقة الاستخدام:
--   1) افتح لوحة تحكم Supabase -> SQL Editor -> New query
--   2) الصق محتوى هذا الملف بالكامل
--   3) اضغط Run
-- ============================================================

-- 1) إنشاء جدول الطلبات
create table if not exists public.orders (
  id             bigint        generated by default as identity primary key,
  created_at     timestamptz   not null default now(),
  invoice_number text          not null,
  items          jsonb         not null default '[]'::jsonb,
  total          numeric(10,3) not null default 0,
  status         text          not null default 'pending'
);

-- 2) تفعيل Real-time على الجدول
--    (replica identity full يجعل أحداث UPDATE و DELETE ترسل الصف كاملاً)
alter table public.orders replica identity full;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename  = 'orders'
  ) then
    alter publication supabase_realtime add table public.orders;
  end if;
end $$;

-- 3) تفعيل حماية الصفوف (RLS) مع سياسات مفتوحة
--    ملاحظة: سياسات مفتوحة لتبسيط التشغيل بدون تسجيل دخول
--    (انظر ملاحظة الأمان في README.md)
alter table public.orders enable row level security;

drop policy if exists "orders_select" on public.orders;
drop policy if exists "orders_insert" on public.orders;
drop policy if exists "orders_update" on public.orders;
drop policy if exists "orders_delete" on public.orders;

create policy "orders_select" on public.orders
  for select to anon, authenticated using (true);

create policy "orders_insert" on public.orders
  for insert to anon, authenticated with check (true);

create policy "orders_update" on public.orders
  for update to anon, authenticated using (true) with check (true);

create policy "orders_delete" on public.orders
  for delete to anon, authenticated using (true);

-- 4) فهرس لتسريع ترتيب الطلبات من الأحدث للأقدم
create index if not exists orders_created_at_idx
  on public.orders (created_at desc);

-- ============================================================
-- 5) جدول يوم العمل (فتح/إغلاق الوردية من لوحة الكاشير)
--    صف واحد بحالة open = اليوم مفتوح، وعند الإغلاق يُخزَّن الملخص
-- ============================================================
create table if not exists public.work_days (
  id           bigint        generated by default as identity primary key,
  opened_at    timestamptz   not null default now(),
  closed_at    timestamptz,
  orders_count integer,
  revenue      numeric(12,3),
  summary      jsonb,
  status       text          not null default 'open'
);

alter table public.work_days enable row level security;

drop policy if exists "work_days_select" on public.work_days;
drop policy if exists "work_days_insert" on public.work_days;
drop policy if exists "work_days_update" on public.work_days;
drop policy if exists "work_days_delete" on public.work_days;

create policy "work_days_select" on public.work_days
  for select to anon, authenticated using (true);

create policy "work_days_insert" on public.work_days
  for insert to anon, authenticated with check (true);

create policy "work_days_update" on public.work_days
  for update to anon, authenticated using (true) with check (true);

create policy "work_days_delete" on public.work_days
  for delete to anon, authenticated using (true);

create index if not exists work_days_status_idx
  on public.work_days (status, opened_at desc);

-- ============================================================
-- 6) منح الصلاحيات على مستوى قاعدة البيانات (GRANT)
--    ⚠️ مهم جداً: سياسات RLS وحدها لا تكفي — دور anon يحتاج
--    صلاحيات الجداول نفسها، وبدون هذا القسم سيظهر خطأ:
--    401 / permission denied for table (كود 42501)
-- ============================================================
grant usage on schema public to anon, authenticated;

grant select, insert, update, delete
  on public.orders, public.work_days
  to anon, authenticated;

grant usage, select on all sequences in schema public
  to anon, authenticated;

-- ضبط الصلاحيات الافتراضية لأي جداول تُنشأ مستقبلاً (غير حرج إذا فشل)
do $$
begin
  alter default privileges in schema public
    grant select, insert, update, delete on tables to anon, authenticated;
  alter default privileges in schema public
    grant usage, select on sequences to anon, authenticated;
exception when others then
  raise notice 'default privileges skipped (not critical): %', sqlerrm;
end $$;
